import re

from helpers.bio_files import default_output_name
from helpers.fastq import open_output, pass_filters, read_one


def filter_fastq(
    input_fastq: str,
    output_fastq: str,
    gc_bounds=(0, 100),
    length_bounds=(0, 2**32),
    quality_threshold: float = 0,
) -> None:
    """
    Filter a FASTQ file and save the passing reads into the filtered/ directory.

    Arguments:
    input_fastq: str — path to the input FASTQ file
    output_fastq: str — output file name (saved into filtered/)
    gc_bounds: tuple | float — GC content interval in percent (default (0, 100));
                               if a single number is passed, it is treated as the upper bound
    length_bounds: tuple | int — length interval (default (0, 2**32));
                                 if a single number is passed, it is treated as the upper bound
    quality_threshold: float — average read quality threshold (Phred+33), default 0

    Returns None. Writes the filtered reads into output_fastq.
    """
    with open(input_fastq) as inp, open_output(output_fastq) as out:
        while True:
            read = read_one(inp)
            if read is None:
                break
            header, seq, plus, qual = read
            if pass_filters(seq, qual, gc_bounds, length_bounds, quality_threshold):
                out.write(f"{header}\n{seq}\n{plus}\n{qual}\n")


def convert_multiline_fasta_to_oneline(
    input_fasta: str,
    output_fasta: str | None = None,
) -> None:
    """
    Convert a multiline FASTA file to the "one line per sequence" format.

    Arguments:
    input_fasta: str — path to the input FASTA file
    output_fasta: str | None — path to the output file; if None, the name is
                               generated by default_output_name

    Returns None. The result is written into output_fasta.
    """
    if output_fasta is None:
        output_fasta = default_output_name(input_fasta)

    header = None
    seq_parts = []
    with open(input_fasta) as inp, open(output_fasta, "w") as out:
        for line in inp:
            line = line.rstrip("\n")
            if line.startswith(">"):
                if header is not None:
                    out.write(f"{header}\n{''.join(seq_parts)}\n")
                header = line
                seq_parts = []
            elif line:
                seq_parts.append(line)
        if header is not None:
            out.write(f"{header}\n{''.join(seq_parts)}\n")


def parse_blast_output(input_file: str, output_file: str) -> None:
    """
    Extract the descriptions of the best hits from a BLAST txt report and
    save them to output_file sorted alphabetically.

    Arguments:
    input_file: str — path to the BLAST txt report
    output_file: str — path to the output file (one description per line)

    Returns None. The result is written into output_file.
    """
    descriptions = set()

    with open(input_file, "r") as f:
        lines = f.readlines()

    i = 0
    n = len(lines)
    while i < n:
        if "Sequences producing significant alignments:" in lines[i]:
            i += 1
            while i < n and "Description" not in lines[i]:
                i += 1
            if i < n:
                i += 1
                while i < n and lines[i].strip() == "":
                    i += 1
                if i < n:
                    hit_line = lines[i].strip()
                    parts = re.split(r"\s{2,}", hit_line)
                    if parts:
                        descriptions.add(parts[0].strip())
        i += 1

    sorted_descriptions = sorted(descriptions)

    with open(output_file, "w") as out:
        out.writelines(desc + "\n" for desc in sorted_descriptions)
